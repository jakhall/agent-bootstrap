#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const USAGE = `Usage: node install-global.mjs [--check] [--no-sync] [--home <dir>]

Installs the agent-bootstrap workflow for Claude Code globally (Windows):
  ~/.claude/CLAUDE.md                  managed block between agent-bootstrap markers
  ~/.claude/agent-bootstrap-sync.ps1   sync shim
  ~/.claude/output-styles/scannable.md "Scannable" output style (set as default when none is set)
  ~/.claude/settings.json              SessionStart + PostToolUse hooks
  ~/.claude/skills/ab-*                generated by the sync script

--check    report what would change; write nothing; exit 1 on drift
--no-sync  skip the sync script (wrappers are not regenerated)
--home     treat <dir> as the home folder (for testing)`;

const args = process.argv.slice(2);
if (args.includes('-h') || args.includes('--help')) { console.log(USAGE); process.exit(0); }
const check = args.includes('--check');
const noSync = args.includes('--no-sync');
const homeIdx = args.indexOf('--home');
const home = homeIdx >= 0 ? resolve(args[homeIdx + 1] ?? '') : homedir();

const claudeDir = join(home, '.claude');
const clone = join(claudeDir, 'agent-bootstrap');
const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const templates = join(repo, '.agents', 'tools', 'global');

const samePath = (a, b) => existsSync(a) && existsSync(b) && realpathSync(a).toLowerCase() === realpathSync(b).toLowerCase();
if (!samePath(repo, clone)) {
  console.error(`The clone must live at ${clone} (the sync script and hooks expect that path); this script runs from ${repo}.\nFix: git clone https://github.com/jakhall/agent-bootstrap.git "${clone}"`);
  process.exit(2);
}

const BEGIN = '<!-- agent-bootstrap:begin (managed by .agents/tools/install-global.mjs; edit .agents/tools/global/CLAUDE.md in the clone) -->';
const END = '<!-- agent-bootstrap:end -->';
const IMPORT_LINE = '@~/.claude/agent-bootstrap/.agents/AGENTS.md';

const results = [];
const read = (p) => (existsSync(p) ? readFileSync(p, 'utf8').replace(/^﻿/, '') : null);
const normalise = (s) => s.replace(/\r\n/g, '\n');

function writeIfChanged(target, desired, label) {
  const current = read(target);
  if (current !== null && normalise(current) === normalise(desired)) {
    results.push({ label, status: 'ok' });
    return;
  }
  results.push({ label, status: current === null ? 'create' : 'update' });
  if (check) return;
  mkdirSync(dirname(target), { recursive: true });
  if (current !== null && label === 'settings.json') copyFileSync(target, `${target}.bak-agent-bootstrap`);
  writeFileSync(target, desired, 'utf8');
}

function installClaudeMd() {
  const target = join(claudeDir, 'CLAUDE.md');
  const block = `${BEGIN}\n${normalise(read(join(templates, 'CLAUDE.md'))).trim()}\n${END}`;
  const current = read(target);
  if (current === null) return writeIfChanged(target, `${block}\n`, 'CLAUDE.md');
  const text = normalise(current);
  const start = text.indexOf(BEGIN.slice(0, 30));
  const end = text.indexOf(END);
  if (start >= 0 && end > start) {
    return writeIfChanged(target, text.slice(0, start) + block + text.slice(end + END.length), 'CLAUDE.md');
  }
  if (text.includes(IMPORT_LINE)) {
    results.push({ label: 'CLAUDE.md', status: 'skip', note: `already imports the workflow outside the managed markers; delete that copy (or wrap it in the markers) and re-run` });
    return;
  }
  writeIfChanged(target, `${text.trimEnd()}\n\n${block}\n`, 'CLAUDE.md');
}

function hookEntry(script, extra) {
  return { ...extra, hooks: [{ type: 'command', command: 'node', args: [join(clone, '.agents', 'hooks', script)], ...HOOK_OPTS[script] }] };
}
const HOOK_OPTS = {
  'session-context.mjs': { timeout: 15, statusMessage: 'Loading project memory' },
  'post-write.mjs': { timeout: 10 },
};

function installSettings() {
  const target = join(claudeDir, 'settings.json');
  const current = read(target);
  let settings;
  try {
    settings = current === null || !current.trim() ? {} : JSON.parse(current);
  } catch (e) {
    results.push({ label: 'settings.json', status: 'skip', note: `not valid JSON (${e.message}); fix it and re-run` });
    return;
  }
  const notes = [];
  settings.hooks ??= {};
  const ensure = (event, script, extra) => {
    const list = (settings.hooks[event] ??= []);
    const present = list.some((e) => (e.hooks ?? []).some((h) => JSON.stringify([h.command, h.args]).includes(script)));
    if (!present) list.push(hookEntry(script, extra));
  };
  ensure('SessionStart', 'session-context.mjs', {});
  ensure('PostToolUse', 'post-write.mjs', { matcher: 'Write|Edit' });
  if (settings.outputStyle === undefined) settings.outputStyle = 'Scannable';
  else if (settings.outputStyle !== 'Scannable') notes.push(`outputStyle is "${settings.outputStyle}"; left as is`);
  const desired = `${JSON.stringify(settings, null, 2)}\n`;
  const before = current === null ? null : JSON.stringify(JSON.parse(current || '{}'), null, 2) + '\n';
  if (before === desired) {
    results.push({ label: 'settings.json', status: 'ok', note: notes.join('; ') || undefined });
    return;
  }
  writeIfChanged(target, desired, 'settings.json');
  if (notes.length) results.at(-1).note = notes.join('; ');
}

writeIfChanged(join(claudeDir, 'agent-bootstrap-sync.ps1'), read(join(templates, 'agent-bootstrap-sync.ps1')), 'agent-bootstrap-sync.ps1');
writeIfChanged(join(claudeDir, 'output-styles', 'scannable.md'), read(join(templates, 'output-styles', 'scannable.md')), 'output-styles/scannable.md');
installClaudeMd();
installSettings();

for (const r of results) console.log(`  ${r.status.padEnd(6)} ${r.label}${r.note ? ` (${r.note})` : ''}`);

let syncFailed = false;
if (!noSync) {
  const shim = join(claudeDir, 'agent-bootstrap-sync.ps1');
  const syncArgs = ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', shim, ...(check ? ['-Check'] : [])];
  if (existsSync(shim)) {
    const run = spawnSync('powershell', syncArgs, { stdio: 'inherit', env: { ...process.env, USERPROFILE: home, HOME: home } });
    syncFailed = run.status !== 0;
  } else {
    console.log('  skip   ab-* wrappers (sync shim not installed yet; re-run without --check)');
    syncFailed = true;
  }
}

const drift = results.some((r) => r.status !== 'ok');
if (check) process.exit(drift || syncFailed ? 1 : 0);
console.log(syncFailed ? '==> done, but the ab-* sync reported a problem (see above).' : '==> done. Restart Claude Code to load the hooks, output style and skills.');
process.exit(syncFailed ? 1 : 0);
